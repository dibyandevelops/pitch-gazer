const UCL_EPL_IDS = new Set(["ars", "avl", "liv", "mci", "mun"]);
const MOCK_FORM: Team["form"][] = [
  ["W", "D", "W", "L", "W"],
  ["W", "W", "D", "W", "W"],
  ["D", "W", "W", "L", "W"],
  ["W", "L", "D", "W", "D"],
  ["W", "D", "W", "W", "L"],
  ["W", "W", "D", "L", "W"],
  ["L", "D", "W", "L", "D"],
  ["D", "W", "L", "W", "D"],
  ["L", "W", "D", "D", "W"],
];

function createTeams(seeds: ClubSeed[], competition: Competition, offset = 0): Team[] {
  return seeds.map((club, index) => {
    const { attack, defense } = club;
    const zoneShift = ((index + offset) % 3) * 0.025;
    const competitions: Competition[] =
      competition === "Premier League"
        ? UCL_EPL_IDS.has(club.id)
          ? ["Premier League", "Champions League"]
          : ["Premier League"]
        : ["Champions League"];
    return {
      id: club.id,
      name: club.name,
      shortName: club.shortName,
      league: competition,
      competitions,
      colors: { primary: club.primary, secondary: club.secondary },
      form: [...MOCK_FORM[(index + offset) % MOCK_FORM.length]!],
      stats: {
        goalsForPerGame: Number((0.85 + attack * 1.1).toFixed(2)),
        goalsAgainstPerGame: Number((2.05 - defense * 0.88).toFixed(2)),
        xgForPerGame: Number((0.82 + attack * 1.08).toFixed(2)),
        xgAgainstPerGame: Number((2.02 - defense * 0.86).toFixed(2)),
        possession: Number(Math.min(0.64, 0.42 + attack * 0.15).toFixed(2)),
        attackZones: [0.33 + zoneShift, 0.34 - zoneShift * 2, 0.33 + zoneShift],
        defenseZones: [0.62 + defense * 0.06, 0.64 + defense * 0.06, 0.62 + defense * 0.06],
      },
    };
  });
}

